#!/usr/bin/env python3
"""Regenerate the sign-off matrix from the verdict files.

The bar (PINK_PONK_PROTOCOL.md, revised 2026-10-26): a task is signed off only
when BOTH `claude_a` and `claude_b`

  * return GREEN on every gating axis: `verdict`, `precision`, `llm_adaptation`;
  * have `comparable` GREEN or NA, and `normalized_ok` GREEN or ABSENT;
  * were launched against the SAME fingerprint, which must also equal the
    task's CURRENT fingerprint (`source_hash.py`), so a fix after review voids it;

and the provenance columns are settled (`github` and `paper_number` each YES or
NONE from at least one reviewer). Verdicts from the retired reviewers (opus5,
codex) are shown for history and never gate.

Usage: python refresh.py [--out PATH]   (default: SIGNOFF_MATRIX.md beside this file)
"""
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import source_hash  # noqa: E402

REVIEWERS = ("claude_a", "claude_b")
LEGACY = ("opus5", "codex")
GATING = ("verdict", "precision", "llm_adaptation")


def load_verdicts():
    V = {}
    for f in glob.glob(os.path.join(HERE, "verdicts", "*.json")):
        try:
            v = json.load(open(f))
        except (OSError, ValueError):
            continue
        V.setdefault(v.get("task"), {})[v.get("reviewer", "?")] = v
    return V


def reviewer_state(v, current_fp):
    """PASS / FAIL / STALE / NOT REVIEWED for one reviewer's verdict."""
    if not v:
        return "NOT REVIEWED"
    if v.get("fingerprint_at_launch") != current_fp:
        return "STALE"
    if any(v.get(ax) != "GREEN" for ax in GATING):
        return "FAIL"
    if v.get("comparable") not in ("GREEN", "NA"):
        return "FAIL"
    if v.get("normalized_ok") not in ("GREEN", "ABSENT", None):
        return "FAIL"
    return "PASS"


def provenance(vs, field):
    vals = [v.get(field) for v in vs if v and v.get(field)]
    for lvl in ("YES", "PARTIAL", "NONE"):
        if lvl in vals:
            return lvl
    return None


def main():
    out = os.path.join(HERE, "SIGNOFF_MATRIX.md")
    if "--out" in sys.argv:
        out = sys.argv[sys.argv.index("--out") + 1]
    tasks = source_hash.paper_core_tasks()
    reg = source_hash._registry()
    V = load_verdicts()
    rows = []
    for t in tasks:
        fp = source_hash.fingerprint(t, reg)[0]
        vs = V.get(t, {})
        a, b = (reviewer_state(vs.get(r), fp) for r in REVIEWERS)
        cur = [vs.get(r) for r in REVIEWERS]
        gh, paper = provenance(cur, "github"), provenance(cur, "paper_number")
        same_launch = (cur[0] and cur[1]
                       and cur[0].get("fingerprint_at_launch") == cur[1].get("fingerprint_at_launch"))
        signed = (a == b == "PASS" and same_launch
                  and gh in ("YES", "NONE") and paper in ("YES", "NONE"))
        legacy = ", ".join(f"{r}:{vs[r].get('verdict', '?')}" for r in LEGACY if r in vs)
        rows.append({"task": t, "fp": fp, "a": a, "b": b, "gh": gh or "—",
                     "paper": paper or "—", "signed": signed, "legacy": legacy or "—"})
    n = len(rows)
    count = lambda pred: sum(1 for r in rows if pred(r))  # noqa: E731
    md = [
        "# Metric sign-off matrix\n\n",
        f"Scope: the **{n} paper-core tasks** (`tests/fixtures/paper_core_tasks.json`). ",
        "Generated by `refresh.py` from `verdicts/*.json`; do not hand-edit. ",
        "The bar is in `PINK_PONK_PROTOCOL.md`.\n\n",
        "| | count | of %d |\n|---|---|---|\n" % n,
        f"| claude_a PASS on the current fingerprint | {count(lambda r: r['a'] == 'PASS')} | |\n",
        f"| claude_b PASS on the current fingerprint | {count(lambda r: r['b'] == 'PASS')} | |\n",
        f"| STALE (code changed after launch) | {count(lambda r: 'STALE' in (r['a'], r['b']))} | |\n",
        f"| **Signed off** | **{count(lambda r: r['signed'])}** | |\n\n",
        "| # | task | fingerprint | claude_a | claude_b | GitHub | paper | signed | legacy (not gating) |\n",
        "|---|---|---|---|---|---|---|---|---|\n",
    ]
    for i, r in enumerate(rows, 1):
        md.append(f"| {i} | `{r['task']}` | `{r['fp']}` | {r['a']} | {r['b']} | {r['gh']} | "
                  f"{r['paper']} | {'**YES**' if r['signed'] else 'no'} | {r['legacy']} |\n")
    with open(out, "w") as fh:
        fh.write("".join(md))
    print(f"wrote {out}: {count(lambda r: r['signed'])} of {n} signed off")


if __name__ == "__main__":
    main()
