#!/usr/bin/env python3
"""Write docs/METRICS.md: every evaluation task, its definition, how it was verified,
its parameters and the design decisions behind them.

Sources, all in this repository: the task registry (HEADLINE_KEYS, SOURCES,
ADAPTATION_NOTE, TOKEN_POLICY, docstrings), task_metadata.py, the shipped
defaults (tasks/configs/defaults.yaml), docs/validation/metrics.json (kernel
evidence), docs/validation/independent_reviews.yaml and
docs/validation/decisions.yaml.

Usage: python scripts/metrics_doc.py [--check]
"""
import inspect
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

EVIDENCE = {
    "release": "Released code executed on the same inputs",
    "published": "Released dataset and a published numerical value",
    "independent": "Independent implementation or scientific library",
    "fixture": "Transcription of the released code or its official fixtures",
    "equation": "Equations and analytic cases (no external reference exists)",
    "proxy": "BLME proxy: an operational definition of its own",
}
FAMILY_TITLES = {
    "geometry": "Geometry", "topology": "Topology", "dynamics": "Dynamics", "repe": "Representation engineering",
    "consistency": "Consistency", "interpretability": "Interpretability", "causality": "Causality",
}
# Tasks the companion study runs alongside the paper-core set, as covariates.
STUDY_COVARIATES = ("consistency_calibration", "interpretability_prediction_entropy")


def _first_paragraph(text):
    text = inspect.cleandoc(text or "")
    para = text.split("\n\n")[0].replace("\n", " ").strip()
    return para


def _fmt(v):
    if isinstance(v, float):
        return f"{v:g}"
    if v is None:
        return "null"
    return str(v)


def build():
    from blme.core import _register_all_tasks
    from blme.registry import _TASK_REGISTRY, get_task
    from blme.task_metadata import task_metadata_dict
    from blme.tasks.config_loader import resolve_task_config
    _register_all_tasks()

    reviews = json.loads((ROOT / "docs/validation/metrics.json").read_text())
    indep = yaml.safe_load((ROOT / "docs/validation/independent_reviews.yaml").read_text())
    decisions = yaml.safe_load((ROOT / "docs/validation/decisions.yaml").read_text())
    core = set(json.loads((ROOT / "tests/fixtures/paper_core_tasks.json").read_text()))
    detailed = sorted(core | set(STUDY_COVARIATES))
    review_of = {}
    for name, b in (indep.get("batches") or {}).items():
        for t, verdict in (b.get("tasks") or {}).items():
            review_of[t] = f"{verdict} ({name}, {b.get('date')}, library {b.get('library')})"

    out = []
    w = out.append
    w("# Evaluation metrics")
    w("")
    w("Generated by `scripts/metrics_doc.py` from the task registry, `task_metadata.py`, the shipped defaults, "
      "`docs/validation/metrics.json`, `docs/validation/independent_reviews.yaml` and `docs/validation/decisions.yaml`. "
      "Edit those, not this file.")
    w("")
    w(f"**{len(_TASK_REGISTRY)} registered tasks.** The {len(core)} paper-core tasks and the companion study's "
      f"{len(STUDY_COVARIATES)} covariates have full entries below; the others are listed at the end.")
    w("")
    w("Each entry gives what the task measures, its headline keys, its references, how it was verified, its "
      "parameters with their shipped defaults, and any design decision. Two kinds of verification are listed:")
    w("")
    w("- **Kernel**: the core computation against a reference on identical inputs (from `docs/validation/metrics.json`).")
    w("- **Pipeline**: an independent re-implementation of the whole path from the model's forward pass, by a "
      "reviewer who did not read the task's code (from `docs/validation/independent_reviews.yaml`).")
    w("")
    w("## Conventions shared by many tasks")
    w("")
    for c in decisions.get("conventions") or []:
        w(f"- **{c['choice']}.** {c['default']} {c.get('why', '')}".rstrip())
    w("")
    w("When several settings are defensible and the evidence does not pick one, the choice is a parameter whose "
      "default is the paper's or released code's protocol; where the alternative is cheap, every run also records it "
      "as a `_meta_` key, so both can be compared without rerunning.")
    w("")

    by_family = {}
    for t in detailed:
        by_family.setdefault(t.split("_")[0], []).append(t)
    for fam in sorted(by_family, key=lambda f: list(FAMILY_TITLES).index(f) if f in FAMILY_TITLES else 99):
        w(f"## {FAMILY_TITLES.get(fam, fam.title())}")
        w("")
        for t in by_family[fam]:
            cls = get_task(t)
            md = task_metadata_dict(t)
            src = getattr(cls, "SOURCES", {}) or {}
            heads = list(getattr(cls, "HEADLINE_KEYS", ()) or ())
            rev = reviews.get(t, {})
            w(f"### `{t}`")
            w("")
            desc = _first_paragraph(cls.__doc__)
            if desc:
                w(desc)
                w("")
            note = getattr(cls, "ADAPTATION_NOTE", None)
            if note:
                w(f"**Protocol.** {' '.join(str(note).split())}")
                w("")
            w(f"**Headline keys.** {', '.join(f'`{h}`' for h in heads) if heads else 'none'}.")
            w("")
            refs = []
            if md.get("papers"):
                refs.append(f"paper: {md['papers']}")
            if src.get("code"):
                refs.append(f"code: `{src['code']}`")
            if src.get("llm_precedent"):
                refs.append(f"LLM precedent: {src['llm_precedent']}")
            if refs:
                w(f"**References.** {'; '.join(refs)}.")
                w("")
            tp = getattr(cls, "TOKEN_POLICY", None)
            if tp:
                w(f"**Tokens.** `{tp}`.")
                w("")
            w("**Verification.**")
            w("")
            w(f"- Kernel: {EVIDENCE.get(rev.get('evidence'), 'not recorded')}. {rev.get('scope', '')}".rstrip())
            w(f"- Pipeline: {review_of.get(t, 'not yet independently re-implemented end to end')}.")
            if rev.get("next_check"):
                w(f"- Next scientific check: {rev['next_check']}")
            w("")
            cfg = {k: v for k, v in resolve_task_config(t).items() if not isinstance(v, (dict, list))}
            if cfg:
                w("**Parameters (shipped defaults).** " + ", ".join(f"`{k}: {_fmt(v)}`" for k, v in sorted(cfg.items())) + ".")
                w("")
            for d in (decisions.get("tasks") or {}).get(t, []):
                param = f" (parameter `{d['parameter']}`)" if d.get("parameter") else ""
                w(f"**Decision: {d['choice']}{param}.** Default: {d['default']}.")
                if d.get("alternatives"):
                    w(f"Alternatives: {'; '.join(d['alternatives'])}.")
                if d.get("recorded"):
                    w(f"Recorded in every run: {', '.join(f'`{r}`' for r in d['recorded'])}.")
                w(f"Why: {d['why']}")
                w("")
    w("## Other registered tasks")
    w("")
    w("Not part of the paper-core set. Their kernels have numerical receipts in `docs/VALIDATION.md`; none has had "
      "an independent end-to-end review.")
    w("")
    w("| Task | Kernel evidence | Headline keys |")
    w("|---|---|---|")
    for t in sorted(set(_TASK_REGISTRY) - set(detailed)):
        heads = list(getattr(get_task(t), "HEADLINE_KEYS", ()) or ())
        ev = EVIDENCE.get(reviews.get(t, {}).get("evidence"), "not recorded").split(":")[0]
        w(f"| `{t}` | {ev} | {', '.join(f'`{h}`' for h in heads) or '—'} |")
    w("")
    return "\n".join(out)


def main():
    text = build()
    path = ROOT / "docs/METRICS.md"
    if "--check" in sys.argv:
        if not path.exists() or path.read_text() != text:
            print("docs/METRICS.md is out of date. Run scripts/metrics_doc.py.")
            sys.exit(1)
        print("docs/METRICS.md is current.")
        return
    path.write_text(text)
    print(f"wrote {path} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
