"""
Generate LaTeX tables for the NeurIPS paper.

Tables produced (as .tex fragments — \input them in main.tex):
  table_model_zoo.tex          — final model list with params/d_model/L/N_heads
  table_main_results.tex       — composite benchmark + top features per model
  table_top_correlations.tex   — top 10 partial correlations with composite
  table_lasso_selection.tex    — LASSO-selected features with R² comparison
  table_edg_per_family.tex     — EDG stats by model family
  table_base_vs_instruct.tex   — paired differences for base/instruct pairs

Usage:
    python scripts/make_tables.py --input-dir results/study_v1
"""

import argparse
import os
from pathlib import Path

import numpy as np
import pandas as pd


# ── LaTeX escaping and formatting helpers ──────────────────────────────

def _esc(s) -> str:
    """Escape LaTeX special characters in a string."""
    if pd.isna(s):
        return "--"
    s = str(s)
    for a, b in [("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"),
                 ("$", r"\$"), ("#", r"\#"), ("_", r"\_"), ("^", r"\^{}"),
                 ("~", r"\~{}"), ("{", r"\{"), ("}", r"\}")]:
        s = s.replace(a, b)
    return s


def _fmt(x, nd: int = 3) -> str:
    """Format a number for a table cell."""
    if pd.isna(x):
        return "--"
    try:
        f = float(x)
    except (TypeError, ValueError):
        return _esc(x)
    if abs(f) < 1e-4 and f != 0:
        return f"${f:.2e}$".replace("e-0", "e-").replace("e+0", "e+")
    if abs(f) >= 1e4:
        return f"${f:.2e}$".replace("e+0", "e+")
    return f"{f:.{nd}f}"


def _fmt_rho(rho, q) -> str:
    """Format a correlation with significance stars."""
    if pd.isna(rho):
        return "--"
    s = f"{rho:+.2f}"
    if pd.notna(q):
        if q < 0.001:
            s += "$^{***}$"
        elif q < 0.01:
            s += "$^{**}$"
        elif q < 0.05:
            s += "$^{*}$"
    return s


def _format_params(n_params_m) -> str:
    """Format parameter count: 124M, 1.5B, etc."""
    if pd.isna(n_params_m):
        return "--"
    n = float(n_params_m)
    if n >= 1000:
        return f"{n/1000:.1f}B"
    return f"{int(round(n))}M"


# ── Table generators ────────────────────────────────────────────────────

def table_model_zoo(agg: pd.DataFrame, out_path: Path):
    """Table 2: Complete model specifications."""
    cols = ["model", "family", "n_params_M", "d_model", "n_layers", "n_heads"]
    present = [c for c in cols if c in agg.columns]
    df = agg[present].copy()
    df = df.sort_values(["family", "n_params_M"])

    # Family display names
    family_display = {
        "gpt2": "GPT-2", "pythia": "Pythia", "llama3": "Llama 3",
        "qwen3.5": "Qwen 3.5", "gemma4": "Gemma 4",
        "olmo": "OLMo", "tinyllama": "TinyLlama", "phi": "Phi",
    }

    lines = [
        "% Generated by scripts/make_tables.py",
        r"\begin{tabular}{@{}llrrrr@{}}",
        r"\toprule",
        r"\textbf{Model} & \textbf{Family} & $N_{\text{params}}$ & $d_{\text{model}}$ & $L$ & $N_{\text{heads}}$ \\",
        r"\midrule",
    ]
    current_family = None
    for _, row in df.iterrows():
        family = family_display.get(row["family"], row["family"])
        if current_family is not None and family != current_family:
            lines.append(r"\midrule")
        current_family = family
        lines.append(
            f"{_esc(row['model'])} & {_esc(family)} & "
            f"{_format_params(row.get('n_params_M'))} & "
            f"{int(row.get('d_model', 0) or 0)} & "
            f"{int(row.get('n_layers', 0) or 0)} & "
            f"{int(row.get('n_heads', 0) or 0)} \\\\"
        )
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    out_path.write_text("\n".join(lines))
    print(f"  wrote {out_path}")


def table_main_results(agg: pd.DataFrame, out_path: Path):
    """Main results table: composite score + select features per model."""
    cols_of_interest = [
        "model", "n_params_M", "composite_benchmark",
        "edg", "geometry_spectral.avg_alpha",
        "geometry_isoscore.isoscore",
        "interpretability_attention_entropy.avg_entropy_total",
        "dynamics_sharpness.hutchinson_trace_per_param",
    ]
    present = [c for c in cols_of_interest if c in agg.columns]
    df = agg[present].copy().sort_values("n_params_M").reset_index(drop=True)

    header = [
        r"\begin{tabular}{@{}lrrrrrrr@{}}",
        r"\toprule",
        r"\textbf{Model} & $N$ & \textbf{Comp.} & \textbf{EDG} & $\alpha$ & \textbf{IsoScore} & $H_{\text{attn}}$ & \textbf{Sharp.}\\",
        r"\midrule",
    ]
    lines = ["% Generated by scripts/make_tables.py"] + header
    for _, row in df.iterrows():
        lines.append(
            f"{_esc(row['model'])} & "
            f"{_format_params(row.get('n_params_M'))} & "
            f"{_fmt(row.get('composite_benchmark'), 3)} & "
            f"{_fmt(row.get('edg'), 2)} & "
            f"{_fmt(row.get('geometry_spectral.avg_alpha'), 2)} & "
            f"{_fmt(row.get('geometry_isoscore.isoscore'), 3)} & "
            f"{_fmt(row.get('interpretability_attention_entropy.avg_entropy_total'), 2)} & "
            f"{_fmt(row.get('dynamics_sharpness.hutchinson_trace_per_param'), 3)} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    out_path.write_text("\n".join(lines))
    print(f"  wrote {out_path}")


def table_top_correlations(partial: pd.DataFrame, out_path: Path,
                            top_n: int = 15, min_n: int = 20):
    """Top N partial correlations with composite, filtered to n>=min_n.

    The min_n filter is critical — per-layer features that only exist for a
    handful of models can have spurious |ρ|=1.0 by chance. At min_n=20 we
    keep only features with adequate power."""
    if partial.empty or "composite_benchmark" not in partial["benchmark"].values:
        print(f"  skipping top correlations (no data)")
        return
    df = partial[partial["benchmark"] == "composite_benchmark"].copy()
    df = df[df["n"] >= min_n].copy()
    if df.empty:
        print(f"  skipping top correlations (no features with n>={min_n})")
        return
    df["abs_rho"] = df["partial_rho"].abs()
    df = df.sort_values("abs_rho", ascending=False).head(top_n)

    lines = [
        "% Generated by scripts/make_tables.py",
        f"% Filter: n >= {min_n} (excludes low-power features that spuriously hit +/-1)",
        r"\begin{tabular}{@{}lrrr@{}}",
        r"\toprule",
        r"\textbf{Feature} & \textbf{Partial $\rho$} & \textbf{$n$} & \textbf{$q$-value}\\",
        r"\midrule",
    ]
    for _, row in df.iterrows():
        lines.append(
            f"\\texttt{{{_esc(row['feature'])}}} & "
            f"{_fmt_rho(row['partial_rho'], row.get('q'))} & "
            f"{int(row.get('n', 0))} & "
            f"{_fmt(row.get('q'), 3)} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    out_path.write_text("\n".join(lines))
    print(f"  wrote {out_path}")


def table_lasso_selection(lasso: pd.DataFrame, out_path: Path, top_n: int = 15):
    """Top N LASSO-selected features."""
    if lasso.empty:
        print(f"  skipping LASSO table (no data)")
        return
    df = lasso.head(top_n)
    lines = [
        "% Generated by scripts/make_tables.py",
        r"\begin{tabular}{@{}lr@{}}",
        r"\toprule",
        r"\textbf{Feature} & \textbf{Coefficient}\\",
        r"\midrule",
    ]
    for _, row in df.iterrows():
        lines.append(
            f"\\texttt{{{_esc(row['feature'])}}} & "
            f"{row['coefficient']:+.4f} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    out_path.write_text("\n".join(lines))
    print(f"  wrote {out_path}")


def table_edg_per_family(agg: pd.DataFrame, out_path: Path):
    """EDG statistics grouped by model family."""
    if "edg" not in agg.columns:
        print(f"  skipping EDG family table (no EDG column)")
        return
    stats = agg.groupby("family").agg(
        n_models=("model", "count"),
        edg_mean=("edg", "mean"),
        edg_std=("edg", "std"),
        edg_min=("edg", "min"),
        edg_max=("edg", "max"),
    ).reset_index()
    stats = stats.sort_values("edg_mean")

    lines = [
        "% Generated by scripts/make_tables.py",
        r"\begin{tabular}{@{}lrrrrr@{}}",
        r"\toprule",
        r"\textbf{Family} & $n$ & \textbf{Mean EDG} & \textbf{Std} & \textbf{Min} & \textbf{Max}\\",
        r"\midrule",
    ]
    for _, row in stats.iterrows():
        lines.append(
            f"{_esc(row['family'])} & {int(row['n_models'])} & "
            f"{_fmt(row['edg_mean'], 3)} & {_fmt(row['edg_std'], 3)} & "
            f"{_fmt(row['edg_min'], 3)} & {_fmt(row['edg_max'], 3)} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    out_path.write_text("\n".join(lines))
    print(f"  wrote {out_path}")


def table_base_vs_instruct(agg: pd.DataFrame, out_path: Path):
    """Paired differences for base-vs-instruct pairs on key metrics."""
    pairs = []
    for _, row in agg.iterrows():
        name = row["model"]
        if name.endswith("-it"):
            base_name = name[:-3]
            base_row = agg[agg["model"] == base_name]
            if len(base_row) == 1:
                pairs.append((base_row.iloc[0], row))
    if not pairs:
        print(f"  skipping base-vs-instruct (no pairs)")
        return

    metrics = [
        ("edg", "EDG"),
        ("interpretability_attention_entropy.avg_entropy_total", r"$H_{\text{attn}}$"),
        ("interpretability_sparsity.global_mean_l0", r"$L_0$"),
        ("repe_refusal_direction.best_layer_separability_auc", "Refusal AUC"),
        ("geometry_isoscore.isoscore", "IsoScore"),
    ]
    metrics = [(k, lbl) for k, lbl in metrics if k in agg.columns]

    col_spec = "l" + "rr" * len(metrics)
    lines = [
        "% Generated by scripts/make_tables.py",
        f"\\begin{{tabular}}{{@{{}}{col_spec}@{{}}}}",
        r"\toprule",
    ]
    header1 = [r"\textbf{Model}"] + [f"\\multicolumn{{2}}{{c}}{{{lbl}}}" for _, lbl in metrics]
    header2 = [""] + ["Base & Inst."] * len(metrics)
    lines.append(" & ".join(header1) + r" \\")
    lines.append(" & ".join(header2) + r" \\")
    lines.append(r"\midrule")

    for base, it in pairs:
        cells = [_esc(base["model"])]
        for k, _ in metrics:
            cells.append(_fmt(base.get(k), 3))
            cells.append(_fmt(it.get(k), 3))
        lines.append(" & ".join(cells) + r" \\")

    lines += [r"\bottomrule", r"\end{tabular}"]
    out_path.write_text("\n".join(lines))
    print(f"  wrote {out_path}")


def _pretty_feature(name: str) -> str:
    """Shorten a feature name like 'interpretability_attention_entropy.avg_entropy_total'
    to something readable inside a table cell, while keeping the underscores escaped."""
    s = str(name)
    # Trim the long task prefix to its category abbreviation
    cat_map = {
        "geometry_": "geom.",
        "interpretability_": "interp.",
        "causality_": "caus.",
        "consistency_": "cons.",
        "dynamics_": "dyn.",
        "repe_": "repe.",
    }
    for full, short in cat_map.items():
        if s.startswith(full):
            s = short + s[len(full):]
            break
    return _esc(s)


def table_base_vs_instruct_shifts(bvi: pd.DataFrame, out_path: Path, top_n: int = 20):
    """Top-N features ranked by absolute cross-model-standardised shift between
    base and instruction-tuned counterparts. Complements the side-by-side
    paired table by surfacing *which* metrics shift the most after SFT.
    """
    if bvi is None or bvi.empty:
        print("  skipping base-vs-instruct shifts (no data)")
        return

    df = bvi.head(top_n).copy()

    lines = [
        "% Generated by scripts/make_tables.py",
        r"\begin{tabular}{@{}lrrrrrr@{}}",
        r"\toprule",
        r"\textbf{Feature} & $n$ & $\Delta$ & $\Delta_{\sigma}$ & $d$ & \textbf{Agree.} & $q$ \\",
        r"\midrule",
    ]
    for _, row in df.iterrows():
        arrow_dir = r"$\uparrow$" if row["mean_delta"] > 0 else r"$\downarrow$"
        agree = f"{row['sign_agreement']:.2f}"
        n_qwen = int(row.get("n_qwen", 0) or 0)
        n_llama = int(row.get("n_llama", 0) or 0)
        n_gemma = int(row.get("n_gemma", 0) or 0)
        n_str = f"{int(row['n_pairs'])}"
        if (n_qwen + n_llama + n_gemma) == int(row["n_pairs"]):
            # Add a tiny per-family breakdown after the n: e.g. "6 (4Q,1L,1G)"
            parts = []
            if n_qwen: parts.append(f"{n_qwen}Q")
            if n_llama: parts.append(f"{n_llama}L")
            if n_gemma: parts.append(f"{n_gemma}G")
            if parts:
                n_str = f"{int(row['n_pairs'])}\\,\\scriptsize{{({','.join(parts)})}}"
        lines.append(
            f"\\texttt{{{_pretty_feature(row['feature'])}}}{arrow_dir} & "
            f"{n_str} & "
            f"{_fmt(row['mean_delta'], 3)} & "
            f"{_fmt(row['std_delta_xmodel'], 2)} & "
            f"{_fmt(row['cohens_d'], 2)} & "
            f"{agree} & "
            f"{_fmt(row.get('wilcoxon_q'), 3)} \\\\"
        )
    lines += [r"\bottomrule", r"\end{tabular}"]
    out_path.write_text("\n".join(lines))
    print(f"  wrote {out_path}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--input-dir", default="results/study_v1")
    ap.add_argument("--output-dir", default=None)
    args = ap.parse_args()

    input_dir = Path(args.input_dir)
    output_dir = Path(args.output_dir) if args.output_dir else input_dir / "tables"
    output_dir.mkdir(parents=True, exist_ok=True)

    agg = pd.read_csv(input_dir / "aggregated.csv")
    analysis_dir = input_dir / "analysis"
    univariate = pd.read_csv(analysis_dir / "univariate.csv") if (analysis_dir / "univariate.csv").exists() else pd.DataFrame()
    partial = pd.read_csv(analysis_dir / "partial.csv") if (analysis_dir / "partial.csv").exists() else pd.DataFrame()
    lasso = pd.read_csv(analysis_dir / "lasso_features.csv") if (analysis_dir / "lasso_features.csv").exists() else pd.DataFrame()
    bvi = pd.read_csv(analysis_dir / "base_vs_instruct.csv") if (analysis_dir / "base_vs_instruct.csv").exists() else pd.DataFrame()

    print(f"Generating LaTeX tables to {output_dir}/")
    table_model_zoo(agg, output_dir / "table_model_zoo.tex")
    table_main_results(agg, output_dir / "table_main_results.tex")
    table_top_correlations(partial, output_dir / "table_top_correlations.tex")
    table_lasso_selection(lasso, output_dir / "table_lasso_selection.tex")
    table_edg_per_family(agg, output_dir / "table_edg_per_family.tex")
    table_base_vs_instruct(agg, output_dir / "table_base_vs_instruct.tex")
    table_base_vs_instruct_shifts(bvi, output_dir / "table_base_vs_instruct_shifts.tex")

    print("\nAll tables generated.")


if __name__ == "__main__":
    main()
